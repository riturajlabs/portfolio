"""Declarative base and constraint naming convention.

One convention for every table keeps Alembic's autogenerate output, the applied
migration and the models comparable. `ck` interpolates `constraint_name`, so
every CHECK is named explicitly in its model — an unnamed CHECK would fail at
metadata construction time instead of producing a surprise in a migration.
"""

from __future__ import annotations

from sqlalchemy import MetaData
from sqlalchemy.orm import DeclarativeBase

NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)